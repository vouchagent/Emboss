"""Render identical content through multiple PDF engines for quality comparison.

Uses the JSON content already generated by llm_comparison.py (from Claude Sonnet 5).

Run:
    python examples/pdf_comparison.py

Output (examples/output/):
    comparison_precision.pdf   - Emboss
    comparison_reportlab.pdf   - ReportLab
    comparison_weasyprint.pdf  - WeasyPrint
    comparison_fpdf2.pdf       - FPDF2
    comparison_report.txt      - Side-by-side feature/size comparison
"""

import json
import time
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

OUTPUT = Path(__file__).parent / "output"
OUTPUT.mkdir(exist_ok=True)

CONTENT_PATH = OUTPUT / "llm_content.json"


def load_content() -> dict:
    if not CONTENT_PATH.exists():
        print("Run llm_comparison.py first to generate content.")
        sys.exit(1)
    return json.loads(CONTENT_PATH.read_text())


# ---------------------------------------------------------------------------
# Engine A: Emboss
# ---------------------------------------------------------------------------

def render_precision(data: dict) -> bytes:
    from emboss import Document, TextRun, Citation

    doc = Document(
        title=data.get("title", ""),
        author=data.get("author", ""),
        language="en-US",
        style="academic",
        header_text=data.get("title", ""),
        page_numbers=True,
        tagged=True,
        toc=True,
    )

    for si, section in enumerate(data.get("sections", [])):
        if si > 0:
            doc.page_break()
        doc.heading(section["heading"], level=section.get("level", 1))
        for elem in section.get("elements", []):
            _add_element_precision(doc, elem)

    return doc.render()


def _add_element_precision(doc, elem):
    from emboss import TextRun, Citation

    etype = elem.get("type", "")
    if etype == "paragraph":
        doc.paragraph(elem["text"])
    elif etype == "paragraph_rich":
        runs = [TextRun(r["text"], bold=r.get("bold", False),
                        italic=r.get("italic", False), color=r.get("color"))
                for r in elem.get("runs", [])]
        doc.paragraph(runs)
    elif etype == "bullets":
        doc.bullets(elem["items"])
    elif etype == "table":
        doc.table(headers=elem["headers"], rows=elem["rows"],
                  caption=elem.get("caption"), stripe=elem.get("stripe", False))
    elif etype == "code":
        doc.code_block(code=elem["code"], language=elem.get("language", "text"),
                       line_numbers=True, theme="dark_modern",
                       caption=elem.get("caption"))
    elif etype == "math":
        doc.math(elem["source"], caption=elem.get("caption"))
    elif etype == "callout":
        doc.callout(elem["text"], variant=elem.get("variant", "info"))
    elif etype == "chart":
        doc.chart(chart_type=elem.get("chart_type", "bar"),
                  labels=elem["labels"],
                  values=[float(v) for v in elem["values"]],
                  title=elem.get("title"))
    elif etype == "footnote":
        doc.footnote(elem["text"], marker=elem.get("marker"))
    elif etype == "bibliography":
        citations = [Citation(key=c["key"], authors=c.get("authors", []),
                              title=c.get("title", ""), year=c.get("year", ""),
                              publisher=c.get("publisher"),
                              journal=c.get("journal"), volume=c.get("volume"),
                              pages=c.get("pages"),
                              entry_type=c.get("entry_type", "article"))
                     for c in elem.get("citations", [])]
        doc.bibliography(citations=citations)


