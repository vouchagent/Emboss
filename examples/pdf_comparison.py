def render_reportlab(data: dict) -> bytes:
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import inch
    from reportlab.lib.colors import HexColor, black, white
    from reportlab.lib.enums import TA_LEFT, TA_CENTER, TA_JUSTIFY
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
        PageBreak, Preformatted, KeepTogether,
    )
    from io import BytesIO

    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=letter,
                            topMargin=72, bottomMargin=72,
                            leftMargin=72, rightMargin=72,
                            title=data.get("title", ""),
                            author=data.get("author", ""))

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle("CustomH1", parent=styles["Heading1"],
                              fontSize=18, spaceAfter=12, spaceBefore=18))
    styles.add(ParagraphStyle("CustomH2", parent=styles["Heading2"],
                              fontSize=14, spaceAfter=10, spaceBefore=14))
    styles.add(ParagraphStyle("CustomBody", parent=styles["Normal"],
                              fontSize=10, leading=14, alignment=TA_JUSTIFY))
    styles.add(ParagraphStyle("CodeStyle", parent=styles["Code"],
                              fontSize=8, leading=10, backColor=HexColor("#1e1e2e"),
                              textColor=white, leftIndent=6, rightIndent=6,
                              spaceBefore=6, spaceAfter=6))
    styles.add(ParagraphStyle("BulletStyle", parent=styles["Normal"],
                              fontSize=10, leading=14, bulletIndent=18,
                              leftIndent=36))
    styles.add(ParagraphStyle("CaptionStyle", parent=styles["Normal"],
                              fontSize=9, leading=11, textColor=HexColor("#666666"),
                              alignment=TA_CENTER, spaceAfter=8))
    styles.add(ParagraphStyle("CalloutStyle", parent=styles["Normal"],
                              fontSize=9, leading=12, leftIndent=12,
                              rightIndent=12, spaceBefore=6, spaceAfter=6,
                              backColor=HexColor("#eff6ff")))
    styles.add(ParagraphStyle("FootnoteStyle", parent=styles["Normal"],
                              fontSize=8, leading=10, textColor=HexColor("#666666")))
    styles.add(ParagraphStyle("BibStyle", parent=styles["Normal"],
                              fontSize=9, leading=11, leftIndent=24,
                              firstLineIndent=-24))

    story = []
    story.append(Paragraph(data.get("title", ""), styles["Title"]))
    if data.get("author"):
        story.append(Paragraph(data["author"], styles["Normal"]))
    story.append(Spacer(1, 12))

    for si, section in enumerate(data.get("sections", [])):
        if si > 0:
            story.append(PageBreak())

        level = section.get("level", 1)
        hstyle = "CustomH1" if level == 1 else "CustomH2"
        story.append(Paragraph(section["heading"], styles[hstyle]))

        for elem in section.get("elements", []):
            _add_element_reportlab(story, elem, styles)

    doc.build(story)
    return buf.getvalue()


def _add_element_reportlab(story, elem, styles):
    from reportlab.platypus import Paragraph, Spacer, Table, TableStyle, Preformatted
    from reportlab.lib.colors import HexColor, black
    from reportlab.lib.units import inch

    etype = elem.get("type", "")

    if etype == "paragraph":
        story.append(Paragraph(_rl_escape(elem["text"]), styles["CustomBody"]))
        story.append(Spacer(1, 6))

    elif etype == "paragraph_rich":
        parts = []
        for r in elem.get("runs", []):
            text = _rl_escape(r["text"])
            if r.get("bold"):
                text = f"<b>{text}</b>"
            if r.get("italic"):
                text = f"<i>{text}</i>"
            if r.get("color"):
                text = f'<font color="#{r["color"]}">{text}</font>'
            parts.append(text)
        story.append(Paragraph("".join(parts), styles["CustomBody"]))
        story.append(Spacer(1, 6))

    elif etype == "bullets":
        for item in elem["items"]:
            story.append(Paragraph(
                f"<bullet>&bull;</bullet> {_rl_escape(item)}",
                styles["BulletStyle"]))
        story.append(Spacer(1, 6))

    elif etype == "table":
        headers = elem["headers"]
        rows = elem["rows"]
        table_data = [headers] + rows
        t = Table(table_data, repeatRows=1)
        style_cmds = [
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#f0f0f0")),
            ("TEXTCOLOR", (0, 0), (-1, 0), black),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("LEADING", (0, 0), (-1, -1), 12),
            ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#cccccc")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]
        if elem.get("stripe"):
            for i in range(1, len(table_data)):
                if i % 2 == 0:
                    style_cmds.append(
                        ("BACKGROUND", (0, i), (-1, i), HexColor("#fafafa")))
        t.setStyle(TableStyle(style_cmds))
        story.append(t)
        if elem.get("caption"):
            story.append(Paragraph(elem["caption"], styles["CaptionStyle"]))
        story.append(Spacer(1, 8))

    elif etype == "code":
        code = elem["code"]
        story.append(Preformatted(code, styles["CodeStyle"]))
        if elem.get("caption"):
            story.append(Paragraph(elem["caption"], styles["CaptionStyle"]))
        story.append(Spacer(1, 8))

    elif etype == "math":
        story.append(Paragraph(
            f'<para alignment="center"><i>{_rl_escape(elem["source"])}</i></para>',
            styles["CustomBody"]))
        if elem.get("caption"):
            story.append(Paragraph(elem["caption"], styles["CaptionStyle"]))

    elif etype == "callout":
        story.append(Paragraph(_rl_escape(elem["text"]), styles["CalloutStyle"]))
        story.append(Spacer(1, 6))

    elif etype == "chart":
        story.append(Paragraph(
            f'<b>{_rl_escape(elem.get("title", "Chart"))}</b>',
            styles["CustomBody"]))
        labels = elem.get("labels", [])
        values = elem.get("values", [])
        for l, v in zip(labels, values):
            story.append(Paragraph(f"  {_rl_escape(str(l))}: {v}", styles["CustomBody"]))
        story.append(Spacer(1, 8))

    elif etype == "footnote":
        marker = elem.get("marker", "*")
        story.append(Paragraph(
            f"<super>{_rl_escape(marker)}</super> {_rl_escape(elem['text'])}",
            styles["FootnoteStyle"]))

    elif etype == "bibliography":
        story.append(Paragraph("References", styles["CustomH2"]))
        for i, c in enumerate(elem.get("citations", []), 1):
            authors = ", ".join(c.get("authors", []))
            title = c.get("title", "")
            year = c.get("year", "")
            venue = c.get("journal") or c.get("publisher", "")
            text = f'[{i}] {_rl_escape(authors)}, "{_rl_escape(title)},"'
            if venue:
                text += f" <i>{_rl_escape(venue)}</i>,"
            text += f" {_rl_escape(year)}."
            story.append(Paragraph(text, styles["BibStyle"]))
        story.append(Spacer(1, 8))


def _rl_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _fpdf2_safe(text: str) -> str:
    out = []
    for ch in text:
        if ord(ch) < 256:
            out.append(ch)
        else:
            out.append("?")
    return "".join(out)


