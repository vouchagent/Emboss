def analyze_pdf(pdf_bytes: bytes, label: str) -> dict:
    features = {
        "label": label,
        "size_bytes": len(pdf_bytes),
        "size_kb": round(len(pdf_bytes) / 1024, 1),
        "valid": pdf_bytes[:5] == b"%PDF-",
        "tagged": b"/StructTreeRoot" in pdf_bytes,
        "has_toc": b"/Outlines" in pdf_bytes,
        "has_metadata": b"/Title" in pdf_bytes,
        "has_lang": b"/Lang" in pdf_bytes,
        "font_count": pdf_bytes.count(b"/Font"),
        "page_count": pdf_bytes.count(b"/Type /Page") - pdf_bytes.count(b"/Type /Pages"),
    }
    return features


def print_comparison(results: list[dict]) -> str:
    lines = []
    lines.append("=" * 78)
    lines.append("  PDF ENGINE COMPARISON REPORT")
    lines.append("=" * 78)
    lines.append("")

    col_w = 20
    header = f"{'Feature':<25}"
    for r in results:
        header += f"{r['label']:>{col_w}}"
    lines.append(header)
    lines.append("-" * len(header))

    fields = [
        ("File Size", lambda r: f"{r['size_kb']} KB"),
        ("Valid PDF", lambda r: "Yes" if r["valid"] else "No"),
        ("PDF/UA Tagged", lambda r: "Yes" if r["tagged"] else "No"),
        ("Table of Contents", lambda r: "Yes" if r["has_toc"] else "No"),
        ("Document Metadata", lambda r: "Yes" if r["has_metadata"] else "No"),
        ("Language Tag", lambda r: "Yes" if r["has_lang"] else "No"),
        ("Font References", lambda r: str(r["font_count"])),
        ("Page Count", lambda r: str(r["page_count"])),
    ]

    for name, fn in fields:
        row = f"{name:<25}"
        for r in results:
            row += f"{fn(r):>{col_w}}"
        lines.append(row)

    lines.append("-" * len(header))

    feature_matrix = [
        "Vector Charts",
        "Math Rendering",
        "Code Highlighting",
        "Deterministic Output",
        "Accessibility Tags",
        "Zero Heavy Deps",
    ]
    engine_features = {
        "Emboss": [True, True, True, True, True, True],
        "ReportLab": [True, False, False, False, False, False],
        "WeasyPrint": [False, False, False, False, False, False],
        "FPDF2": [False, False, False, False, False, False],
    }

    lines.append("")
    lines.append(f"{'Capability':<25}", )
    for r in results:
        lines[-1] += f"{r['label']:>{col_w}}"
    lines.append("-" * len(lines[-1]))

    for i, feat in enumerate(feature_matrix):
        row = f"{feat:<25}"
        for r in results:
            has = engine_features.get(r["label"], [False] * 6)
            val = has[i] if i < len(has) else False
            row += f"{'Yes':>{col_w}}" if val else f"{'No':>{col_w}}"
        lines.append(row)

    lines.append("")
    lines.append("=" * 78)

    report = "\n".join(lines)
    print(report)
    return report


def main():
    data = load_content()

    engines = [
        ("Emboss", "comparison_precision.pdf", render_precision),
        ("ReportLab", "comparison_reportlab.pdf", render_reportlab),
        ("WeasyPrint", "comparison_weasyprint.pdf", render_weasyprint),
        ("FPDF2", "comparison_fpdf2.pdf", render_fpdf2),
    ]

    results = []
    timings = {}

    for label, filename, renderer in engines:
        print(f"Rendering with {label}...")
        try:
            t0 = time.perf_counter()
            pdf_bytes = renderer(data)
            elapsed = time.perf_counter() - t0
            timings[label] = elapsed

            if pdf_bytes:
                path = OUTPUT / filename
                path.write_bytes(pdf_bytes)
                info = analyze_pdf(pdf_bytes, label)
                info["time_ms"] = round(elapsed * 1000)
                results.append(info)
                print(f"  Done: {info['size_kb']} KB, {info['time_ms']} ms")
            else:
                print(f"  Skipped (no output)")
        except Exception as e:
            print(f"  Error: {e}")

    report = print_comparison(results)

    timing_lines = ["\nRender Times:"]
    for label, ms in sorted(timings.items(), key=lambda x: x[1]):
        timing_lines.append(f"  {label:<20} {ms*1000:>8.0f} ms")
    timing_report = "\n".join(timing_lines)
    print(timing_report)

    report_path = OUTPUT / "comparison_report.txt"
    report_path.write_text(report + "\n" + timing_report + "\n")
    print(f"\nReport saved: {report_path}")
    print(f"PDFs saved in: {OUTPUT}")


if __name__ == "__main__":
    main()
