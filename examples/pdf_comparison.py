def render_fpdf2(data: dict) -> bytes:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=72)
    pdf.set_margins(72, 72, 72)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, data.get("title", ""), new_x="LMARGIN", new_y="NEXT")
    if data.get("author"):
        pdf.set_font("Helvetica", "I", 10)
        pdf.cell(0, 8, data["author"], new_x="LMARGIN", new_y="NEXT")
    pdf.ln(8)

    for si, section in enumerate(data.get("sections", [])):
        if si > 0:
            pdf.add_page()

        level = section.get("level", 1)
        size = 16 if level == 1 else 13
        pdf.set_font("Helvetica", "B", size)
        pdf.cell(0, size * 0.8, section["heading"], new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

        for elem in section.get("elements", []):
            _add_element_fpdf2(pdf, elem)

    return bytes(pdf.output())


def _add_element_fpdf2(pdf, elem):
    from fpdf import FPDF

    etype = elem.get("type", "")
    page_width = pdf.w - pdf.l_margin - pdf.r_margin

    if etype == "paragraph":
        pdf.set_font("Helvetica", "", 10)
        pdf.multi_cell(0, 5, _fpdf2_safe(elem["text"]))
        pdf.ln(3)

    elif etype == "paragraph_rich":
        pdf.set_font("Helvetica", "", 10)
        for r in elem.get("runs", []):
            style = ""
            if r.get("bold"):
                style += "B"
            if r.get("italic"):
                style += "I"
            pdf.set_font("Helvetica", style, 10)
            pdf.write(5, _fpdf2_safe(r["text"]))
        pdf.ln(8)

    elif etype == "bullets":
        pdf.set_font("Helvetica", "", 10)
        for item in elem["items"]:
            pdf.cell(12, 5, "-")
            pdf.multi_cell(page_width - 12, 5, _fpdf2_safe(item))
            pdf.ln(1)
        pdf.ln(3)

    elif etype == "table":
        headers = elem["headers"]
        rows = elem["rows"]
        col_count = len(headers)
        col_w = page_width / col_count

        pdf.set_font("Helvetica", "B", 9)
        for h in headers:
            pdf.cell(col_w, 7, _fpdf2_safe(str(h)[:30]), border=1)
        pdf.ln()

        pdf.set_font("Helvetica", "", 9)
        for row in rows:
            for i, cell in enumerate(row):
                pdf.cell(col_w, 6, _fpdf2_safe(str(cell)[:30]), border=1)
            pdf.ln()

        if elem.get("caption"):
            pdf.set_font("Helvetica", "I", 8)
            pdf.cell(0, 5, elem["caption"], new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

    elif etype == "code":
        pdf.set_font("Courier", "", 8)
        pdf.set_fill_color(30, 30, 46)
        pdf.set_text_color(205, 214, 244)
        for line in elem["code"].split("\n"):
            pdf.cell(0, 4, _fpdf2_safe(line[:100]), new_x="LMARGIN", new_y="NEXT", fill=True)
        pdf.set_text_color(0, 0, 0)
        if elem.get("caption"):
            pdf.set_font("Helvetica", "I", 8)
            pdf.cell(0, 5, elem["caption"], new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

    elif etype == "math":
        pdf.set_font("Helvetica", "I", 11)
        pdf.cell(0, 8, _fpdf2_safe(elem["source"]), new_x="LMARGIN", new_y="NEXT", align="C")
        if elem.get("caption"):
            pdf.set_font("Helvetica", "I", 8)
            pdf.cell(0, 5, elem["caption"], new_x="LMARGIN", new_y="NEXT", align="C")
        pdf.ln(3)

    elif etype == "callout":
        pdf.set_fill_color(239, 246, 255)
        pdf.set_font("Helvetica", "", 9)
        pdf.multi_cell(0, 5, _fpdf2_safe(elem["text"]), fill=True)
        pdf.set_fill_color(255, 255, 255)
        pdf.ln(4)

    elif etype == "chart":
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 7, elem.get("title", "Chart"), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)
        for l, v in zip(elem.get("labels", []), elem.get("values", [])):
            pdf.cell(0, 5, f"  {l}: {v}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

    elif etype == "footnote":
        pdf.set_font("Helvetica", "", 8)
        marker = elem.get("marker", "*")
        pdf.cell(0, 4, _fpdf2_safe(f"[{marker}] {elem['text']}"), new_x="LMARGIN", new_y="NEXT")

    elif etype == "bibliography":
        pdf.set_font("Helvetica", "B", 13)
        pdf.cell(0, 10, "References", new_x="LMARGIN", new_y="NEXT")
        for i, c in enumerate(elem.get("citations", []), 1):
            pdf.set_font("Helvetica", "", 9)
            authors = ", ".join(c.get("authors", []))
            title = c.get("title", "")
            year = c.get("year", "")
            venue = c.get("journal") or c.get("publisher", "")
            ref = f'[{i}] {authors}, "{title},"'
            if venue:
                ref += f" {venue},"
            ref += f" {year}."
            pdf.multi_cell(0, 4, _fpdf2_safe(ref))
            pdf.ln(2)


